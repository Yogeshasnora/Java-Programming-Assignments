// Assignment 3: Star and Number Patterns
// Print a square of stars with 4 rows and 4 columns. Use one loop inside another loop.

public class program_01 {
public static void main(String[] args) {
for (int i = 1; i <= 4; i++) {
for (int j = 1; j <= 4; j++) {
System.out.print("*");
}
System.out.println();
}
}
}
